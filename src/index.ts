#!/usr/bin/env node
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";
import { loadConfig } from "./config.js";
import { FlowClient, explainApiError } from "./flow.js";

const cfg = loadConfig();
const flow = new FlowClient(cfg);

const server = new McpServer({ name: "googleflow-mcp", version: "0.1.0" });

type Content =
  | { type: "text"; text: string }
  | { type: "image"; data: string; mimeType: string };

const json = (value: unknown): Content => ({ type: "text", text: JSON.stringify(value, null, 2) });

/** Wraps a handler so errors come back to the model as readable tool errors instead of crashing. */
function safe<A>(fn: (args: A) => Promise<Content[]>) {
  return async (args: A) => {
    try {
      return { content: await fn(args) };
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      return { content: [{ type: "text" as const, text: `Error: ${explainApiError(message, cfg)}` }], isError: true };
    }
  };
}

const MAX_PREVIEW_BYTES = 1_500_000;

// ---------------- Video ----------------

server.registerTool(
  "flow_generate_video",
  {
    title: "Generate video (Veo, like Google Flow)",
    description: [
      "Create a short video clip with Veo (the model behind Google Flow).",
      "Modes: text-to-video (prompt only); frames-to-video (startImage, optional endImage);",
      "ingredients-to-video (referenceImages for consistent characters/objects/style).",
      "Write a cinematic prompt: subject, action, setting, camera move, lens, lighting, style, and any dialogue in quotes plus sound effects/ambience.",
      "Images can be asset ids (from flow_list_assets / flow_generate_image) or local file paths.",
      "Rendering takes 1-6 minutes; by default the tool waits. If it returns status=pending, call flow_check_operation later.",
      "Files are saved locally and the result includes their paths.",
    ].join(" "),
    inputSchema: {
      prompt: z.string().optional().describe("Detailed description of the shot. Required unless startImage is given."),
      negativePrompt: z.string().optional().describe("What to avoid, e.g. 'text overlays, blurry, cartoon'."),
      aspectRatio: z.enum(["16:9", "9:16"]).optional().describe("16:9 landscape (default) or 9:16 vertical."),
      resolution: z.enum(["720p", "1080p", "4k"]).optional().describe("Output resolution. Not every model supports every value."),
      durationSeconds: z.number().int().min(4).max(8).optional().describe("Clip length in seconds (Veo 3.1: 4, 6 or 8)."),
      fast: z.boolean().optional().describe("Use the cheaper/faster model (FLOW_VIDEO_FAST_MODEL)."),
      model: z.string().optional().describe("Override model id, e.g. veo-3.1-generate-preview."),
      startImage: z.string().optional().describe("First frame: asset id or local image path."),
      endImage: z.string().optional().describe("Last frame: asset id or local image path (needs startImage)."),
      referenceImages: z.array(z.string()).max(3).optional().describe("Up to 3 'ingredient' images (asset ids or paths)."),
      generateAudio: z
        .boolean()
        .optional()
        .describe("Vertex AI only. Leave unset on the Gemini API: Veo 3.x there always generates audio, so describe sounds in the prompt."),
      seed: z.number().int().optional().describe("Vertex AI only; ignored on the Gemini API."),
      numberOfVideos: z.number().int().min(1).max(4).optional(),
      personGeneration: z.enum(["allow_all", "allow_adult", "dont_allow"]).optional(),
      wait: z.boolean().optional().describe("Wait for the render (default true). false returns an operationName immediately."),
      timeoutSeconds: z.number().int().min(10).max(1800).optional().describe("Max seconds to wait (default 540)."),
    },
  },
  safe(async (args) => {
    const res = await flow.generateVideo(args);
    return [json(res)];
  }),
);

server.registerTool(
  "flow_extend_video",
  {
    title: "Extend video (Flow 'Extend')",
    description:
      "Continue a previously generated Veo video with a new prompt, like Flow's Extend / Scene Builder. " +
      "The source must be a video asset generated by this server (Gemini API keeps the remote file ~2 days, 720p only).",
    inputSchema: {
      videoId: z.string().describe("Asset id of the video to extend (e.g. vid_...)."),
      prompt: z.string().describe("What happens next in the scene."),
      model: z.string().optional(),
      wait: z.boolean().optional(),
      timeoutSeconds: z.number().int().min(10).max(1800).optional(),
    },
  },
  safe(async ({ videoId, prompt, model, wait, timeoutSeconds }) => {
    const res = await flow.generateVideo({ extendVideoId: videoId, prompt, model, wait, timeoutSeconds, resolution: "720p" });
    return [json(res)];
  }),
);

server.registerTool(
  "flow_check_operation",
  {
    title: "Check video render",
    description:
      "Check (and optionally wait for) a pending Veo operation. When finished, the video is downloaded and its asset id/path returned. " +
      "Call without operationName to list all pending renders.",
    inputSchema: {
      operationName: z.string().optional(),
      waitSeconds: z.number().int().min(0).max(1800).optional().describe("How long to keep polling (default 0 = check once)."),
    },
  },
  safe(async ({ operationName, waitSeconds }) => {
    if (!operationName) return [json({ pending: await flow.store.listPending() })];
    return [json(await flow.checkOperation(operationName, waitSeconds ?? 0))];
  }),
);

// ---------------- Image ----------------

server.registerTool(
  "flow_generate_image",
  {
    title: "Generate or edit image (Nano Banana)",
    description: [
      "Create or edit images with Google's image models (Nano Banana / Imagen), as in Flow's image tools.",
      "Without inputImages: text-to-image. With inputImages: edit, restyle, or combine them according to the prompt.",
      "Use it to build characters, props and keyframes, then pass the returned asset ids to flow_generate_video",
      "as startImage/endImage/referenceImages. Returns local paths and a preview.",
    ].join(" "),
    inputSchema: {
      prompt: z.string().describe("Description of the image or the edit to make."),
      inputImages: z.array(z.string()).optional().describe("Asset ids or local paths to edit/compose."),
      aspectRatio: z
        .enum(["1:1", "2:3", "3:2", "3:4", "4:3", "4:5", "5:4", "9:16", "16:9", "21:9"])
        .optional()
        .describe("Use 16:9 or 9:16 for video keyframes."),
      imageSize: z.enum(["1K", "2K", "4K"]).optional(),
      numberOfImages: z.number().int().min(1).max(4).optional(),
      model: z.string().optional().describe("Override model id, e.g. gemini-3-pro-image-preview or imagen-4.0-generate-001."),
      preview: z.boolean().optional().describe("Return the image inline so you can see it (default true)."),
    },
  },
  safe(async ({ preview, ...args }) => {
    const res = await flow.generateImage(args);
    const content: Content[] = [
      json({ assets: res.assets, modelText: res.text, note: res.assets.length ? undefined : "No image returned." }),
    ];
    if (preview !== false) {
      for (const p of res.previews) {
        if (Buffer.byteLength(p.data, "base64") <= MAX_PREVIEW_BYTES) {
          content.push({ type: "image", data: p.data, mimeType: p.mimeType });
        }
      }
    }
    return content;
  }),
);

// ---------------- Library ----------------

server.registerTool(
  "flow_list_assets",
  {
    title: "List generated assets",
    description: "List videos and images created by this server (newest first), with ids, prompts and local paths.",
    inputSchema: {
      kind: z.enum(["video", "image"]).optional(),
      limit: z.number().int().min(1).max(200).optional(),
    },
    annotations: { readOnlyHint: true },
  },
  safe(async ({ kind, limit }) => [
    json({ outputDir: cfg.outputDir, assets: await flow.store.listAssets(kind, limit ?? 50) }),
  ]),
);

server.registerTool(
  "flow_list_models",
  {
    title: "List available video/image models",
    description: "List the Veo / image model ids your API key can use, plus the defaults this server is configured with.",
    inputSchema: {},
    annotations: { readOnlyHint: true },
  },
  safe(async () => [
    json({
      defaults: { video: cfg.videoModel, videoFast: cfg.videoFastModel, image: cfg.imageModel },
      backend: cfg.useVertex ? `vertex-ai (${cfg.project}/${cfg.location})` : "gemini-api",
      available: await flow.listModels(),
    }),
  ]),
);

// ---------------- Prompt: director mode ----------------

server.registerPrompt(
  "flow_director",
  {
    title: "Flow director",
    description: "Turn a story idea into a shot list and render it with Veo, step by step.",
    argsSchema: {
      idea: z.string().describe("The story, ad or scene you want to make."),
      style: z.string().optional().describe("Visual style, e.g. 'cinematic 35mm', 'Pixar-like 3D', 'documentary'."),
      format: z.string().optional().describe("'16:9' or '9:16'."),
    },
  },
  ({ idea, style, format }) => ({
    messages: [
      {
        role: "user",
        content: {
          type: "text",
          text: [
            `You are a film director using the Google Flow tools (googleflow MCP).`,
            `Idea: ${idea}`,
            style ? `Style: ${style}` : "",
            `Format: ${format || "16:9"}`,
            "",
            "1. Write a short shot list (3-6 shots, 8s each): subject, action, camera, lighting, audio/dialogue.",
            "2. If characters or products must stay consistent, create them first with flow_generate_image and reuse the asset ids as referenceImages or startImage.",
            "3. Render each shot with flow_generate_video (use fast=true for drafts). Use flow_extend_video to continue a shot.",
            "4. Report the local file paths of every clip in order, so they can be edited together.",
            "Ask me before rendering more than 6 clips, since each one costs credits.",
          ]
            .filter(Boolean)
            .join("\n"),
        },
      },
    ],
  }),
);

async function main() {
  const transport = new StdioServerTransport();
  await server.connect(transport);
  console.error(`googleflow-mcp ready. Output: ${cfg.outputDir}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
